plugins {
    id("com.android.application")
}

android {
    namespace = "io.github.blzkz.formpdfreader"
    compileSdk = 36

    defaultConfig {
        applicationId = "io.github.blzkz.formpdfreader"
        minSdk = 26
        // Google Play requires API 36 for new apps and updates (August 2026).
        targetSdk = 36
        versionCode = 23
        versionName = "0.11.2"
        // The Rust core and PDFium are built for arm64 (scripts/android/build-rust.sh).
        ndk {
            abiFilters += listOf("arm64-v8a")
            // Symbols of the native libraries in the App Bundle, for Google
            // Play's crash and ANR reports (the APK gets them stripped).
            debugSymbolLevel = "SYMBOL_TABLE"
        }
    }

    // The NDK that built the Rust core strips the native libraries and
    // extracts their symbols (its version has to be given too).
    System.getenv("ANDROID_NDK_HOME")?.takeIf { it.isNotBlank() && file("$it/source.properties").exists() }?.let { dir ->
        ndkPath = dir
        file("$dir/source.properties").readLines()
            .firstOrNull { it.startsWith("Pkg.Revision") }
            ?.substringAfter("=")?.trim()
            ?.let { ndkVersion = it }
    }

    // Release signing: the upload key for Google Play, from the environment
    // (the CI decodes it from the repository secrets; see
    // scripts/android/crear-clave-de-subida.sh). Without it, local and pull
    // request builds are signed with the debug key.
    val keystore = System.getenv("ANDROID_KEYSTORE")?.takeIf { it.isNotBlank() && file(it).exists() }
    signingConfigs {
        if (keystore != null) {
            create("upload") {
                storeFile = file(keystore)
                storeType = "pkcs12"
                storePassword = System.getenv("ANDROID_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("ANDROID_KEY_ALIAS")
                keyPassword = System.getenv("ANDROID_KEY_PASSWORD") ?: System.getenv("ANDROID_KEYSTORE_PASSWORD")
            }
        }
    }

    buildTypes {
        // Local test builds: installed beside the app from Google Play (another
        // id and name), so trying a build never touches its data.
        debug {
            applicationIdSuffix = ".prueba"
            versionNameSuffix = "-prueba"
            // -Pminificar: the same R8 and resource shrinking as the release,
            // to try them on a device beside the app from Google Play.
            if (project.hasProperty("minificar")) {
                isMinifyEnabled = true
                isShrinkResources = true
                proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            }
        }
        release {
            // R8: reduce y ofusca el código (Google Play lo pide). Las reglas
            // de JNA, en proguard-rules.pro. También quita los recursos que
            // no se usan (de las librerías, sobre todo).
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfig = signingConfigs.findByName("upload") ?: signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    // Kotlin bindings generated by uniffi (scripts/android/build-rust.sh). As
    // Kotlin sources: AGP's built-in Kotlin does not compile .kt from java.srcDir.
    sourceSets["main"].kotlin.srcDir("src/generated/kotlin")
    // Licences shown in Settings (scripts/android/build-rust.sh).
    sourceSets["main"].assets.srcDir("src/generated/assets")
    // The native libraries stay uncompressed in the APK and are loaded from
    // there (no copy extracted at install: half the space on the device).
}

dependencies {
    // uniffi's Kotlin bindings call the Rust library through JNA.
    implementation("net.java.dev.jna:jna:5.15.0@aar")
    implementation("androidx.appcompat:appcompat:1.7.0")
    implementation("androidx.core:core-ktx:1.15.0")
    implementation("com.google.android.material:material:1.12.0")
    implementation("androidx.recyclerview:recyclerview:1.3.2")
    // DNIe over NFC: the official Spanish library (GPL-2.0 / EUPL-1.1).
    // jmulticard-crypto includes the Bouncy Castle classes it uses (MIT).
    implementation("es.gob.afirma.jmulticard:jmulticard:2.1")
    implementation("es.gob.afirma.jmulticard:jmulticard-crypto:2.1")
    implementation("es.gob.afirma.jmulticard:jmulticard-android:2.1")
}
